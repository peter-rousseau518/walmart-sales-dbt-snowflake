/* =====================================================================
   Walmart Sales Pipeline - CI/CD service user and least-privilege role
   Run once as ACCOUNTADMIN, after the three 01_raw_layer_<env>.sql scripts.

   TRANSFORMER can: use the warehouse, read each RAW schema, build in
   WALMART_DEV (throwaway CI_PR_ schemas) and in the ANALYTICS schema of
   STAGING and PROD. It cannot create databases, users or roles.

   Replace before running:
     <YOUR_USERNAME>   your Snowflake login (SELECT CURRENT_USER();)
     <PUBLIC_KEY>      contents of rsa_key.pub WITHOUT the BEGIN/END lines
   ===================================================================== */

USE ROLE ACCOUNTADMIN;

-- 1. Role (granted to SYSADMIN so ACCOUNTADMIN and the dashboard inherit it)
CREATE ROLE IF NOT EXISTS TRANSFORMER;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE TRANSFORMER;

-- 2. Read RAW in every environment
GRANT USAGE  ON DATABASE WALMART_DEV                       TO ROLE TRANSFORMER;
GRANT USAGE  ON SCHEMA   WALMART_DEV.RAW                   TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA WALMART_DEV.RAW    TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA WALMART_DEV.RAW    TO ROLE TRANSFORMER;

GRANT USAGE  ON DATABASE WALMART_STAGING                    TO ROLE TRANSFORMER;
GRANT USAGE  ON SCHEMA   WALMART_STAGING.RAW                TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA WALMART_STAGING.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA WALMART_STAGING.RAW TO ROLE TRANSFORMER;

GRANT USAGE  ON DATABASE WALMART_PROD                       TO ROLE TRANSFORMER;
GRANT USAGE  ON SCHEMA   WALMART_PROD.RAW                   TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA WALMART_PROD.RAW    TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA WALMART_PROD.RAW    TO ROLE TRANSFORMER;

-- 3. Build: throwaway PR schemas in DEV
GRANT CREATE SCHEMA ON DATABASE WALMART_DEV TO ROLE TRANSFORMER;

-- 4. Build: take ownership of ANALYTICS in STAGING and PROD (and everything already in it),
--    so dbt running as TRANSFORMER can replace the tables and views
GRANT OWNERSHIP ON SCHEMA WALMART_STAGING.ANALYTICS TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA WALMART_STAGING.ANALYTICS TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL VIEWS  IN SCHEMA WALMART_STAGING.ANALYTICS TO ROLE TRANSFORMER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON SCHEMA WALMART_PROD.ANALYTICS TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA WALMART_PROD.ANALYTICS TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL VIEWS  IN SCHEMA WALMART_PROD.ANALYTICS TO ROLE TRANSFORMER COPY CURRENT GRANTS;

-- 5. Service user for GitHub Actions: key-pair login only, no password
CREATE USER IF NOT EXISTS GITHUB_CI
  TYPE              = SERVICE
  DEFAULT_ROLE      = TRANSFORMER
  DEFAULT_WAREHOUSE = COMPUTE_WH
  RSA_PUBLIC_KEY    = '<PUBLIC_KEY>'
  COMMENT           = 'GitHub Actions CI/CD for walmart-sales-dbt-snowflake';
GRANT ROLE TRANSFORMER TO USER GITHUB_CI;

-- 6. Let you run STAGING/PROD locally as TRANSFORMER if you ever need to
GRANT ROLE TRANSFORMER TO USER <YOUR_USERNAME>;

-- Checks
SHOW GRANTS TO ROLE TRANSFORMER;
DESC USER GITHUB_CI;   -- RSA_PUBLIC_KEY_FP should be filled in
